# Начальные значения переменных
steps_in_part = 0
floor = 0
total_seconds = 0

# Константы
PARTS_IN_FLOOR = 2      # пролётов на этаж (подъём + спуск)
SEC_LIVE_IN_STEP = 10   # секунд жизни за одну ступеньку

print("\n=================\n")

# Описание программы
print("Данная программа считает на сколько секунд увеличится ваша жизнь при поднятии пешком на этаж, на котором вы живёте")

print()

# Ввод: ступеньки в пролёте
steps_in_part = int(input("Введите количество ступенек в пролёте: "))

print()

# Ввод: этаж
floor = int(input("Введите этаж, на котором вы живёте: "))

# Расчёт: ступеньки * пролёты * этажи * секунды за ступеньку
total_seconds = steps_in_part * PARTS_IN_FLOOR * floor * SEC_LIVE_IN_STEP

print()

# Вывод результата
print(f"Ваша жизнь при поднятии на {floor} этаж увеличится на {total_seconds} секунд")

print("\n=================\n")
